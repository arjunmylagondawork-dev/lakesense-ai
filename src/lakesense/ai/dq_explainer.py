"""AI data-quality explainer: turns raw rule results into an incident report."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from lakesense.ai import prompts
from lakesense.ai.llm import LLMClient, get_llm
from lakesense.config import Settings
from lakesense.logging_utils import get_logger

log = get_logger(__name__)
SEVERITY_WEIGHT = {"error": 1.0, "warn": 0.3}


def health_score(results: list[dict[str, Any]]) -> float:
    """0-100 score: per table, 100 minus the severity-weighted failure rates of its rules;
    the overall score is the mean over tables. Errors cost more than warnings."""
    if not results:
        return 100.0
    penalties: dict[str, float] = {}
    for r in results:
        weight = SEVERITY_WEIGHT.get(r["severity"], 1.0)
        penalties[r.get("table", "_")] = penalties.get(r.get("table", "_"), 0.0) + (1 - r["pass_rate"]) * weight
    scores = [max(0.0, 100 * (1 - p)) for p in penalties.values()]
    return round(sum(scores) / len(scores), 2)


def build_prompt(results: list[dict[str, Any]], score: float) -> str:
    failing = [r for r in results if r["failed_rows"] > 0]
    return (f"Health score: {score}\nTotal checks: {len(results)}\n"
            f"Failing checks (JSON):\n{json.dumps(failing, indent=2)}")


def explain(settings: Settings, llm: LLMClient | None = None) -> Path:
    llm = llm or get_llm()
    reports = settings.paths.reports
    results = json.loads((reports / "dq_results.json").read_text(encoding="utf-8"))
    score = health_score(results)
    quarantined_dims = sorted({r["table"] for r in results
                               if r["table"] != "orders" and r["severity"] == "error" and r["failed_rows"]})
    body = llm.complete(
        prompts.DQ_SYSTEM, build_prompt(results, score), task="dq_explain",
        context={"results": results, "health_score": score, "quarantined_dims": quarantined_dims},
    )
    out = reports / "dq_report.md"
    out.write_text(f"# Data Quality Report\n\n_Generated by LLM provider: `{llm.name}`_\n\n{body}\n",
                   encoding="utf-8")
    (reports / "dq_summary.json").write_text(json.dumps({"health_score": score}, indent=2))
    log.info("DQ health score %.2f -> %s", score, out)
    return out
